function getR1BodyDefault(grade: Grade, subject: Subject): string {
  const low = grade <= 2;
  const mid = grade >= 3 && grade <= 4;
  // high: grade >= 5

  if (subject === '國語') {
    if (low) {
      return '低年段國語：以口語與圖像線索理解字詞與短敘事為主；認知負荷放在「意義提取與簡單預測」，避免過長篇章與多重隱含推論。';
    }
    if (mid) {
      return '中年段國語：段落整合、修辭帶來的心智表徵與「為什麼這樣寫」的初階推論並進；題組常以「4-4-2」節奏安排新知、易錯點與小綜合，讀寫策略可逐步遷移。';
    }
    return '高年段國語：弦外之音、立場與證據、文言／現代語感切換；認知上需監控「表層訊息／深層意圖」，題組仍保留適量錨題，避免連續高階推論造成疲勞。';
  }

  if (subject === '數學') {
    if (low) {
      return '低年段數學：具體量感與操作經驗優先，符號與算式是「情境的縮寫」；認知重點在單步意義對應，少抽象跳躍。';
    }
    if (mid) {
      return '中年段數學：題意轉譯為數學結構（算用合一）、表徵轉換與迷思監控；題組常以「4-4-2」節奏輪替概念建立、典型錯誤與小綜合，維持可負荷的推理步數。';
    }
    return '高年段數學：多步驟推理、比例／速率與圖表訊息並存；認知上需同時處理「程序正確性」與「結果合理性檢核」，題組穿插較直觀題作為節奏調節。';
  }

  if (subject === '自然') {
    if (low) {
      return '低年段自然：感官觀察與分類描述為主，科學詞彙貼近具體經驗；認知重點在「看見變化、說得出差異」，少抽象模型。';
    }
    if (mid) {
      return '中年段自然：對照與變因的初階覺察、「觀察→解釋」要能接回證據；認知負荷放在探究語彙與因果鏈，題組節奏避免連續開放假設。';
    }
    return '高年段自然：系統觀（物質、能量、交互作用）與證據詮釋並重；認知上需整合圖像、數據與敘述，題組保留步驟鷹架以降低連續抽象推理負荷。';
  }

  if (subject === '社會') {
    if (low) {
      return '低年段社會：自我、家庭與社區的具體經驗；認知重點在「辨識角色與規範」，地圖與方位以生活尺度呈現。';
    }
    if (mid) {
      return '中年段社會：時空脈絡下的因果與簡單觀點取替；認知負荷放在「證據與立場的對應」，題組避免只考地名年代而無推理任務。';
    }
    return '高年段社會：歷史敘事與當代議題的連結、價值與公平的初階思辨；認知上需區分事實、推論與立場，題組節奏宜穿插較具體的情境題。';
  }

  if (subject === '英語') {
    if (low) {
      return '低年段英語：聽覺辨識、模仿與核心詞彙意義；認知負荷放在「音義連結與固定語塊」，句型長度與資訊量需嚴格控管。';
    }
    if (mid) {
      return '中年段英語：短對話與意群理解，能用上下文線索推測意義；認知重點在溝通意圖而非瑣碎規則，題組節奏避免連續生詞堆疊。';
    }
    return '高年段英語：篇章訊息整合與策略性猜測（線索、銜接詞）；認知上需監控「局部句義／整段目的」，題組仍保留較直白題作為信心錨點。';
  }

  // 生活
  if (low) {
    return '低年段生活：安全、常規與身體界線等具體經驗；認知負荷放在「辨識與命名」，題材與語彙需貼近日常。';
  }
  if (mid) {
    return '中年段生活：跨領域經驗的簡單整合與問題解決；認知重點在「把做法說清楚」，避免抽象口號式選項。';
  }
  return '高年段生活：自主規劃與風險意識的初階判斷；認知上需連結學校與社區資源，題組節奏宜具體可操作。';
}

function getR1Body(grade: Grade, semester: Semester, subject: Subject): string {
  const key = `${grade}_${semester}_${subject}`;
  const hit = R1_FOCUS[key];
  if (hit) return hit;
  return getR1BodyDefault(grade, subject);
}

