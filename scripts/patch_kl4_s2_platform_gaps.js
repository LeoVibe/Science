function nowStamp() {
  const d = new Date();
  const p = (n) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())} ${p(d.getHours())}:${p(d.getMinutes())}`;
}

function safeStem(t) {
  return t.replace(/[／]/g, '_').replace(/[\/\\:*?"<>|]/g, '_').replace(/\s+/g, '_').replace(/_+/g, '_').replace(/^_|_$/g, '').slice(0, 80);
}

function quoteBody(raw) {
  return raw
    .trim()
    .split(/\r?\n/)
    .map((l) => (l.startsWith('>') ? l : `> ${l}`))
    .join('\n');
}

