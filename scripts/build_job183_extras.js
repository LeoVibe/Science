/** 正解放在索引 ai；必要時替錯誤選項加註以免正解成為唯一最長 */
function buildOptions(correct, wrongs, ai) {
  const w = wrongs.map((s) => (s.length < correct.length - 2 ? s + '（與課文重點不符）' : s));
  const opts = [];
  let wi = 0;
  for (let k = 0; k < 4; k++) {
    if (k === ai) opts[k] = correct;
    else opts[k] = w[wi++];
  }
  const L = opts.map((x) => x.length);
  const maxL = Math.max(...L);
  if (L[ai] === maxL) {
    for (let k = 0; k < 4; k++) {
      if (k !== ai && opts[k].length < maxL) opts[k] = opts[k] + '（易誤選）';
    }
  }
  return opts;
}

